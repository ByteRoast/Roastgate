using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using System.Text.Json.Serialization;

namespace Roastgate.Core.Nginx.Generation;

/// <summary>
/// The wizard writes its settings (JSON, one line) and a hash of the generated body in comments at the top of the file.
/// That is what lets it reopen its own files, and notice when somebody edited one by hand.
/// </summary>
public static class SiteMetadataFormat
{
    public const string SpecPrefix = "# roastgate-spec: ";
    public const string HashPrefix = "# roastgate-body-sha256: ";

    private static readonly JsonSerializerOptions JsonOptions = CreateJsonOptions();

    public static string Compose(SiteSpec spec, string body)
    {
        string normalizedBody = NormalizeBody(body);

        StringBuilder builder = new();
        builder.Append(
            "# Generated by the Roastgate wizard. Editing this file by hand is fine: the wizard will then warn\n");
        builder.Append("# before it replaces your changes.\n");
        builder.Append(SpecPrefix).Append(JsonSerializer.Serialize(spec, JsonOptions)).Append('\n');
        builder.Append(HashPrefix).Append(Hash(normalizedBody)).Append('\n');
        builder.Append('\n');
        builder.Append(normalizedBody);

        return builder.ToString();
    }

    /// <summary>True when the file carries the wizard header (cheap check used by the lists).</summary>
    public static bool IsWizardFile(string content)
    {
        foreach (string line in FirstLines(content, 8))
        {
            if (line.StartsWith(SpecPrefix, StringComparison.Ordinal))
            {
                return true;
            }
        }

        return false;
    }

    public static SiteMetadata Read(string content)
    {
        string normalized = content.Replace("\r\n", "\n").Replace('\r', '\n');
        string[] lines = normalized.Split('\n');

        int specIndex = Array.FindIndex(
            lines,
            0,
            Math.Min(lines.Length, 8),
            (string line) => line.StartsWith(SpecPrefix, StringComparison.Ordinal)
        );

        if (specIndex < 0)
        {
            return new SiteMetadata(MetadataStatus.None, null);
        }

        int hashIndex = specIndex + 1;

        if (hashIndex >= lines.Length || !lines[hashIndex].StartsWith(HashPrefix, StringComparison.Ordinal))
        {
            return new SiteMetadata(MetadataStatus.Unreadable, null);
        }

        SiteSpec? spec;

        try
        {
            spec = JsonSerializer.Deserialize<SiteSpec>(lines[specIndex][SpecPrefix.Length..], JsonOptions);
        }
        catch (JsonException)
        {
            return new SiteMetadata(MetadataStatus.Unreadable, null);
        }

        if (spec is null)
        {
            return new SiteMetadata(MetadataStatus.Unreadable, null);
        }

        string recordedHash = lines[hashIndex][HashPrefix.Length..].Trim();

        // The body starts after the header and the blank line that follows it.
        string body = string.Join('\n', lines.Skip(hashIndex + 2));

        bool intact = string.Equals(Hash(NormalizeBody(body)), recordedHash, StringComparison.OrdinalIgnoreCase);

        return new SiteMetadata(intact ? MetadataStatus.Intact : MetadataStatus.EditedByHand, spec);
    }

    private static string NormalizeBody(string body)
    {
        string text = body.Replace("\r\n", "\n").Replace('\r', '\n').TrimEnd();

        return text.Length == 0 ? string.Empty : text + "\n";
    }

    private static string Hash(string body)
    {
        return Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(body))).ToLowerInvariant();
    }

    private static IEnumerable<string> FirstLines(string content, int count)
    {
        int start = 0;

        for (int line = 0; line < count && start < content.Length; line++)
        {
            int end = content.IndexOf('\n', start);

            if (end < 0)
            {
                end = content.Length;
            }

            yield return content[start..end].TrimEnd('\r');

            start = end + 1;
        }
    }

    private static JsonSerializerOptions CreateJsonOptions()
    {
        JsonSerializerOptions options = new(JsonSerializerDefaults.Web) { WriteIndented = false };

        options.Converters.Add(new JsonStringEnumConverter());

        return options;
    }
}
