using Roastgate.Core.Nginx.Generation;

namespace Roastgate.Tests.Generation;

public sealed class SiteMetadataTests
{
    private const string Body = "server {\n    listen 80;\n    server_name app.example.com;\n}\n";

    private static SiteSpec Spec()
    {
        return new SiteSpec
        {
            ServerNames = ["app.example.com", "www.example.com"],
            Upstream = "http://127.0.0.1:3000",
            EnableTls = true,
            CertificatePath = "/etc/ssl/c.pem",
            CertificateKeyPath = "/etc/ssl/k.pem",
            Whitelists = ["alice.conf"],
            ProxyTimeoutSeconds = 90,
            ExtraServerDirectives = "location /health {\n    return 200;\n}",
        };
    }

    [Fact]
    public void A_composed_file_starts_with_the_header_then_a_blank_line_then_the_body()
    {
        string text = SiteMetadataFormat.Compose(Spec(), Body);
        string[] lines = text.Split('\n');

        Assert.StartsWith("# Generated by the Roastgate wizard", lines[0]);
        Assert.StartsWith(SiteMetadataFormat.SpecPrefix, lines[2]);
        Assert.StartsWith(SiteMetadataFormat.HashPrefix, lines[3]);
        Assert.Equal(string.Empty, lines[4]);
        Assert.EndsWith("\n" + Body, text);
    }

    [Fact]
    public void The_settings_stay_on_one_line_even_when_they_contain_line_breaks()
    {
        string text = SiteMetadataFormat.Compose(Spec(), Body);
        string specLine = text.Split('\n').Single((string line) => line.StartsWith(
            SiteMetadataFormat.SpecPrefix,
            StringComparison.Ordinal)
        );

        Assert.Contains("location /health {\\n    return 200;\\n}", specLine);
        Assert.Contains("\"kind\":\"ReverseProxy\"", specLine);
    }

    [Fact]
    public void A_file_the_wizard_just_wrote_reads_back_as_intact_with_the_same_settings()
    {
        SiteSpec spec = Spec();

        string text = SiteMetadataFormat.Compose(spec, Body);

        SiteMetadata metadata = SiteMetadataFormat.Read(text);

        Assert.Equal(MetadataStatus.Intact, metadata.Status);
        Assert.NotNull(metadata.Spec);

        // Compose is deterministic, so identical settings give identical text (record equality would compare list references).
        Assert.Equal(text, SiteMetadataFormat.Compose(metadata.Spec, Body));
        Assert.Equal(spec.ServerNames, metadata.Spec.ServerNames);
        Assert.Equal(spec.ExtraServerDirectives, metadata.Spec.ExtraServerDirectives);
        Assert.Equal(SiteKind.ReverseProxy, metadata.Spec.Kind);
        Assert.Equal(90, metadata.Spec.ProxyTimeoutSeconds);
    }

    [Fact]
    public void A_static_site_keeps_its_kind()
    {
        SiteSpec spec = new()
        {
            Kind = SiteKind.StaticSite,
            ServerNames = ["a.example.com"],
            RootDirectory = "/var/www/a"
        };

        SiteMetadata metadata = SiteMetadataFormat.Read(SiteMetadataFormat.Compose(spec, Body));

        Assert.Equal(SiteKind.StaticSite, metadata.Spec!.Kind);
        Assert.Equal("/var/www/a", metadata.Spec.RootDirectory);
    }

    [Fact]
    public void Changing_the_body_by_hand_is_noticed()
    {
        string text = SiteMetadataFormat.Compose(Spec(), Body);

        SiteMetadata metadata = SiteMetadataFormat.Read(text.Replace("listen 80;", "listen 81;"));

        Assert.Equal(MetadataStatus.EditedByHand, metadata.Status);
        Assert.NotNull(metadata.Spec);
    }

    [Fact]
    public void Appending_a_directive_by_hand_is_noticed()
    {
        string text = SiteMetadataFormat.Compose(Spec(), Body);

        Assert.Equal(MetadataStatus.EditedByHand, SiteMetadataFormat.Read(text + "# my own note\n").Status);
    }

    [Theory]
    [InlineData("\n\n\n")]
    [InlineData("   \n")]
    public void Trailing_whitespace_is_not_an_edit(string suffix)
    {
        string text = SiteMetadataFormat.Compose(Spec(), Body);

        Assert.Equal(MetadataStatus.Intact, SiteMetadataFormat.Read(text.TrimEnd() + suffix).Status);
    }

    [Fact]
    public void Windows_line_endings_are_not_an_edit()
    {
        string text = SiteMetadataFormat.Compose(Spec(), Body);

        Assert.Equal(MetadataStatus.Intact, SiteMetadataFormat.Read(text.Replace("\n", "\r\n")).Status);
    }

    [Fact]
    public void A_plain_config_is_not_a_wizard_file()
    {
        SiteMetadata metadata = SiteMetadataFormat.Read("server {\n    listen 80;\n}\n");

        Assert.Equal(MetadataStatus.None, metadata.Status);
        Assert.Null(metadata.Spec);
    }

    [Theory]
    [InlineData("# roastgate-spec: {not json\n# roastgate-body-sha256: abc\n\nserver {}\n")]
    [InlineData("# roastgate-spec: {\"kind\":\"Nonsense\"}\n# roastgate-body-sha256: abc\n\nserver {}\n")]
    [InlineData("# roastgate-spec: null\n# roastgate-body-sha256: abc\n\nserver {}\n")]
    [InlineData("# roastgate-spec: {}\nserver {}\n")]
    public void A_corrupted_header_is_reported_as_unreadable_instead_of_throwing(string text)
    {
        SiteMetadata metadata = SiteMetadataFormat.Read(text);

        Assert.Equal(MetadataStatus.Unreadable, metadata.Status);
        Assert.Null(metadata.Spec);
    }

    [Fact]
    public void Text_in_a_setting_cannot_forge_a_second_header_line()
    {
        SiteSpec spec = Spec() with { ExtraServerDirectives = "x;\n# roastgate-body-sha256: forged" };

        string text = SiteMetadataFormat.Compose(spec, Body);

        Assert.Equal(1, text.Split('\n').Count((string line) => line.StartsWith(
            SiteMetadataFormat.HashPrefix,
            StringComparison.Ordinal)
        ));

        Assert.Equal(MetadataStatus.Intact, SiteMetadataFormat.Read(text).Status);
    }

    [Fact]
    public void Wizard_files_are_recognised_from_their_first_lines_only()
    {
        Assert.True(SiteMetadataFormat.IsWizardFile(SiteMetadataFormat.Compose(Spec(), Body)));
        Assert.False(SiteMetadataFormat.IsWizardFile("server {}\n"));
        Assert.False(SiteMetadataFormat.IsWizardFile(string.Join(
            '\n',
            Enumerable.Repeat("# filler", 20)) + "\n# roastgate-spec: {}\n")
        );

        Assert.False(SiteMetadataFormat.IsWizardFile(string.Empty));
    }

    [Fact]
    public void Keeps_the_fancyindex_options_through_the_metadata_round_trip()
    {
        SiteSpec spec = new()
        {
            Kind = SiteKind.StaticSite,
            ServerNames = ["files.example.com"],
            RootDirectory = "/srv/files",
            FancyIndex = new FancyIndexOptions
            {
                DefaultSort = FancyIndexSort.DateDescending,
                ExactSize = false,
                LocalTime = true,
                Header = "/.nginxy/header.html",
                Footer = "/.nginxy/footer.html",
                Ignore = ["radarr", "uploads"],
                TimeFormat = "%d-%b-%Y %H:%M",
            },
        };

        string text = SiteMetadataFormat.Compose(spec, Body);

        SiteMetadata metadata = SiteMetadataFormat.Read(text);

        Assert.Equal(MetadataStatus.Intact, metadata.Status);

        FancyIndexOptions options = Assert.IsType<FancyIndexOptions>(metadata.Spec!.FancyIndex);

        Assert.Equal(FancyIndexSort.DateDescending, options.DefaultSort);
        Assert.False(options.ExactSize);
        Assert.True(options.LocalTime);
        Assert.Equal("/.nginxy/header.html", options.Header);
        Assert.Equal("/.nginxy/footer.html", options.Footer);
        Assert.Equal(["radarr", "uploads"], options.Ignore);
        Assert.Equal("%d-%b-%Y %H:%M", options.TimeFormat);
        Assert.Contains("\"defaultSort\":\"DateDescending\"", text);
    }

    [Fact]
    public void Reads_a_spec_saved_before_fancyindex_existed()
    {
        string text = "# roastgate-spec: {\"kind\":\"StaticSite\",\"serverNames\":[\"a.example.com\"]}\n" +
                      "# roastgate-body-sha256: abc\n\nserver {}\n";

        SiteMetadata metadata = SiteMetadataFormat.Read(text);

        Assert.NotNull(metadata.Spec);
        Assert.Null(metadata.Spec.FancyIndex);
        Assert.Equal(SiteKind.StaticSite, metadata.Spec.Kind);
    }
}
